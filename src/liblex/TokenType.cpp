	case TokenType::StringType:
		return "StringType";
	case TokenType::UnitType:
		return "UnitType";
	case TokenType::ArrayType:
		return "ArrayType";
	case TokenType::Plus:
		return "Plus";
	case TokenType::Minus:
		return "Minus";
	case TokenType::Multiply:
		return "Multiply";
	case TokenType::Divide:
		return "Divide";
	case TokenType::Modulo:
		return "Modulo";
	case TokenType::Equal:
		return "Equal";
	case TokenType::NotEqual:
		return "NotEqual";
