		return "TemplateIdentifier";
	case TokenType::TemplateBegin:
		return "TemplateBegin";
	case TokenType::TemplateEnd:
		return "TemplateEnd";
	case TokenType::Break:
		return "Break";
	case TokenType::Continue:
		return "Continue";
	case TokenType::Do:
		return "Do";
	case TokenType::Else:
		return "Else";
	case TokenType::False:
		return "False";
	case TokenType::For:
		return "For";
	case TokenType::Fun:
		return "Fun";
	case TokenType::If:
		return "If";
	case TokenType::In:
		return "In";
	case TokenType::Return:
		return "Return";
	case TokenType::Struct:
		return "Struct";
	case TokenType::True:
		return "True";
	case TokenType::Val:
		return "Val";
	case TokenType::Var:
		return "Var";
	case TokenType::While:
		return "While";
	case TokenType::IntType:
		return "IntType";
	case TokenType::DoubleType:
		return "DoubleType";
	case TokenType::BooleanType:
