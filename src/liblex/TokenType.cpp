		return "DoubleLiteral";
	case TokenType::CharLiteral:
		return "CharLiteral";
	case TokenType::StringBegin:
		return "StringBegin";
	case TokenType::StringText:
		return "StringText";
	case TokenType::StringEnd:
		return "StringEnd";
